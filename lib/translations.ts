export type LangCode = keyof typeof TRANSLATIONS

const CODES: Record<string, LangCode> = { English: "en", Spanish: "es", Mandarin: "zh", Hindi: "hi", Arabic: "ar" }

/** "Spanish" -> "es". Unknown names fall back to English. */
export function langCode(language: string): LangCode {
  return CODES[language] ?? "en"
}

// Falls back to English, then to the key, so a missing translation never shows a blank.
export function getTranslation(language: string, key: string): string {
  const table = TRANSLATIONS[langCode(language)] as Record<string, string>
  return table[key] || (TRANSLATIONS.en as Record<string, string>)[key] || key
}

/** A level's name or description in the player's language, from the level's own translations. */
export function levelText(
  level: { name: string; description: string; translations?: Partial<Record<string, { name?: string; description?: string }>> },
  field: "name" | "description",
  language: string,
): string {
  return level.translations?.[langCode(language)]?.[field] || level[field]
}
